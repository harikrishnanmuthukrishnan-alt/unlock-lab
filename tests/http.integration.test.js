import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const file=path.join(os.tmpdir(),`unlock-lab-integration-${process.pid}.json`);
process.env.DATA_FILE=file;
process.env.NODE_ENV='test';
const {server}=await import('../server.js');
const day=()=>{const d=new Date();d.setUTCDate(d.getUTCDate()+2);return d.toISOString().slice(0,10)};

await test('HTTP integration: requests, owner approval, condition return and audit + CSRF',async(t)=>{
 await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
 t.after(async()=>{await new Promise(resolve=>server.close(resolve));fs.rmSync(file,{force:true});});
 const base=`http://127.0.0.1:${server.address().port}`;
 const post=async(route,body,cookie='')=>{const response=await fetch(base+route,{method:'POST',headers:{'Content-Type':'application/json','X-Unlock-Client':'web',Cookie:cookie},body:JSON.stringify(body)});return {status:response.status,data:await response.json(),cookie:response.headers.get('set-cookie')?.split(';')[0]};};
 const get=async(cookie)=>{const response=await fetch(base+'/api/bootstrap',{headers:{Cookie:cookie}});return {status:response.status,data:await response.json(),cookie:response.headers.get('set-cookie')?.split(';')[0]};};
 let student=await post('/api/demo-login',{userId:'student1'});
 assert.equal(student.status,200);const studentCookie=student.cookie;
 let owner=await post('/api/demo-login',{userId:'owner1'});
 assert.equal(owner.status,200);const ownerCookie=owner.cookie;
 const bad=await fetch(base+'/api/action',{method:'POST',headers:{'Content-Type':'application/json',Cookie:studentCookie},body:JSON.stringify({action:'reset'})});
 assert.equal(bad.status,403);
 let created=await post('/api/action',{action:'request',resourceId:'r1',date:day(),start:'10:00',end:'11:30',purpose:'Create prototype for capstone research'},studentCookie);
 assert.equal(created.status,200,created.data.error);const bookingId=created.data.bookingId;
 const studentApproval=await post('/api/action',{action:'review',bookingId,decision:'approve',note:'verified'},studentCookie);
 assert.equal(studentApproval.status,403);
 const reviewed=await post('/api/action',{action:'review',bookingId,decision:'approve',note:'Staff verified prerequisites'},ownerCookie);
 assert.equal(reviewed.status,200,reviewed.data.error);
 const checked=await post('/api/action',{action:'checkin',bookingId,code:'MK4-2048',condition:'Excellent',note:'Looks good'},studentCookie);
 assert.equal(checked.status,200,checked.data.error);
 const checkedOut=await post('/api/action',{action:'checkout',bookingId,condition:'Good',note:'All accessories accounted for'},studentCookie);
 assert.equal(checkedOut.status,200,checkedOut.data.error);
 const returned=await post('/api/action',{action:'confirmReturn',bookingId,note:'Confirmed by responsible manager'},ownerCookie);
 assert.equal(returned.status,200,returned.data.error);
 const result=await get(studentCookie);
 assert.equal(result.status,200);
 const booking=result.data.bookings.find(b=>b.id===bookingId);
 assert.equal(booking.status,'returned');
 const activity=result.data.events.filter(e=>e.bookingId===bookingId).map(x=>x.type);
 assert.deepEqual(activity.slice().sort(),['checkin','checkout','decision','request','return'].sort());
 assert.ok(fs.existsSync(file),'database should persist');
 assert.equal(result.data.resources.find(x=>x.id==='r4').code,undefined,'no handover code for unapproved equipment');
});
